import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs'
fs.mkdirSync('shots/redesign', { recursive: true })
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
try {
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
await page.goto('http://127.0.0.1:5173/')
await page.waitForFunction(() => window.__qa?.game.getState().all.length > 600 && document.querySelector('canvas')?.getAttribute('role') === 'application')
await page.waitForTimeout(1400)
await page.screenshot({ path: 'shots/redesign/title.png' })
await page.keyboard.press('Enter')
await page.waitForFunction(() => window.__qa.game.getState().phase === 'question')
await page.keyboard.press('Space')
await page.waitForTimeout(1000)
await page.screenshot({ path: 'shots/redesign/play.png' })
const point = await page.evaluate(async () => {
  const {layout} = await import('/src/scene/Play.tsx')
  const s=window.__qa.game.getState(), L=layout(s.view,s.deck[s.round]), p=L.optPos(0)
  return {x:(p.x/s.view.w+.5)*innerWidth,y:(.5-p.y/s.view.h)*innerHeight}
})
await page.mouse.move(point.x,point.y)
await page.waitForTimeout(350)
assert.equal(await page.evaluate(() => window.__qa.game.getState().hovered),0)
await page.screenshot({ path: 'shots/redesign/hover.png' })
await page.mouse.down()
await page.waitForTimeout(200)
await page.screenshot({ path: 'shots/redesign/pressed.png' })
await page.mouse.up()
await page.waitForFunction(() => window.__qa.game.getState().phase === 'reveal')
await page.waitForTimeout(1750)
await page.screenshot({ path: 'shots/redesign/reveal.png' })
await page.keyboard.press('s')
await page.waitForTimeout(500)
await page.screenshot({ path: 'shots/redesign/settings.png' })
await page.setViewportSize({ width: 390, height: 844 })
await page.waitForTimeout(500)
await page.screenshot({ path: 'shots/redesign/settings-phone.png' })
await page.keyboard.press('Escape')
await page.waitForTimeout(300)
await page.screenshot({ path: 'shots/redesign/play-phone.png' })
await page.keyboard.press('Home')
await page.waitForTimeout(500)
await page.screenshot({ path: 'shots/redesign/title-phone.png' })
assert.deepEqual(errors,[])
console.log('Mouse hover, press, release and reveal checked; desktop and phone screenshots saved.')
} finally { await browser.close() }
