import { chromium } from 'playwright'
import fs from 'node:fs'
import assert from 'node:assert/strict'
fs.mkdirSync('shots/expressive',{recursive:true})
const browser=await chromium.launch({args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist']})
try {
const page=await browser.newPage({viewport:{width:1280,height:800},locale:'en-GB',timezoneId:'Europe/London'})
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
await page.goto(process.argv[2] ?? 'http://127.0.0.1:5173/')
await page.waitForFunction(()=>window.__qa?.game.getState().all.length>600 && document.querySelector('canvas')?.getAttribute('role')==='application')
await page.waitForTimeout(1800)
await page.screenshot({path:'shots/expressive/title.png'})
await page.keyboard.press('Enter')
await page.waitForFunction(()=>window.__qa.game.getState().phase==='question')
await page.keyboard.press('Space')
await page.keyboard.press('ArrowRight')
await page.waitForTimeout(800)
await page.screenshot({path:'shots/expressive/play.png'})
const right=await page.evaluate(()=>window.__qa.game.getState().options.findIndex(o=>o.correct)+1)
await page.keyboard.press(String(right))
await page.waitForFunction(()=>window.__qa.game.getState().phase==='reveal')
await page.waitForTimeout(250)
await page.screenshot({path:'shots/expressive/yes.png'})
await page.waitForTimeout(500)
await page.screenshot({path:'shots/expressive/confetti.png'})
await page.waitForTimeout(2100)
await page.screenshot({path:'shots/expressive/reveal.png'})
await page.keyboard.press('Enter')
await page.waitForFunction(()=>window.__qa.game.getState().phase==='question')
await page.keyboard.press('Space')
const wrong=await page.evaluate(()=>window.__qa.game.getState().options.findIndex(o=>!o.correct)+1)
await page.keyboard.press(String(wrong))
await page.waitForFunction(()=>window.__qa.game.getState().phase==='reveal')
await page.waitForTimeout(200)
await page.screenshot({path:'shots/expressive/nope.png'})
await page.keyboard.press('Home')
await page.keyboard.press('h')
await page.waitForTimeout(600)
await page.screenshot({path:'shots/expressive/history.png'})
await page.keyboard.press('Enter')
await page.waitForFunction(()=>window.__qa.game.getState().reviewGameId!==null)
await page.waitForTimeout(600)
await page.screenshot({path:'shots/expressive/history-detail.png'})
await page.setViewportSize({width:320,height:568})
await page.waitForTimeout(700)
await page.screenshot({path:'shots/expressive/history-phone.png'})
await page.keyboard.press('Escape')
await page.waitForTimeout(400)
await page.screenshot({path:'shots/expressive/history-list-phone.png'})
await page.evaluate(()=>{
 const s=window.__qa.game.getState(), deck=s.all.slice(0,10)
 const sample=(id,n,completed,at)=>({id,startedAt:at,completedAt:completed?at+400000:null,total:10,answers:deck.slice(0,n).map((q,i)=>({quoteId:q.id,picked:i%2?q.decoys[0].name:q.answer.name,correct:i%2===0,at:at+i*10000}))})
 window.__qa.game.setState({games:Array.from({length:7},(_,i)=>sample('preview'+i,10-i%4,i%4===0,Date.now()-i*86400000))})
})
await page.waitForTimeout(500)
await page.screenshot({path:'shots/expressive/history-many-phone.png'})
await page.setViewportSize({width:1280,height:720})
await page.waitForTimeout(500)
await page.screenshot({path:'shots/expressive/history-many-desktop.png'})
await page.evaluate(()=>{
 const s=window.__qa.game.getState(), deck=s.all.toSorted((a,b)=>b.quote.length-a.quote.length).slice(0,10)
 window.__qa.game.setState({screen:'summary',phase:'summary',phaseAt:performance.now(),deck,gameStartedAt:Date.now()-300000,score:5,results:deck.map((_,i)=>i%2?'wrong':'right'),picks:deck.map((q,i)=>i%2?q.decoys[0].name:q.answer.name)})
})
await page.waitForTimeout(2900)
await page.screenshot({path:'shots/expressive/summary-long.png'})
await page.setViewportSize({width:320,height:568})
await page.waitForTimeout(650)
await page.screenshot({path:'shots/expressive/summary-phone.png'})
assert.deepEqual(errors,[])
console.log('Expressive preview captured: title, live reactions, game history, review, pagination and long-quote results.')
} finally {await browser.close()}
